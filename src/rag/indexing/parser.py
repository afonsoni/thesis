"""
PDF-to-Markdown parser using marker_single CLI tool.

Wraps the existing marker_single subprocess call with proper logging,
return values, and integration with the config system.
"""

import glob
import logging
import os
import re
import subprocess
from typing import List, Optional

from src.utils.config_loader import config

logger = logging.getLogger(__name__)

# Markdown image, with or without a target: marker emits ![](_page_0_Picture_0.jpeg),
# and its LLM pass occasionally invents ![alt](https://...) or a bare ![alt].
_IMAGE_RE = re.compile(r"!\[[^\]]*\](\([^)]*\))?")


def strip_images(text: str) -> str:
    """Remove markdown image references and the blank runs they leave behind."""
    text = _IMAGE_RE.sub("", text)
    return re.sub(r"\n{3,}", "\n\n", text)


def strip_images_in_file(md_path: str) -> None:
    with open(md_path, encoding="utf-8") as fh:
        text = fh.read()
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(strip_images(text))


def parse_pdfs(
    pdf_dir: Optional[str] = None,
    output_dir: Optional[str] = None,
    output_format: str = "markdown",
) -> List[str]:
    """
    Parse all PDF files in *pdf_dir* and convert them to markdown via ``marker_single``.

    Args:
        pdf_dir: Directory containing the source PDFs.
                 Falls back to ``config.paths.raw_data``.
        output_dir: Where to write the generated ``.md`` files.
                    Falls back to ``<config.paths.markdown_data>/_raw``; the
                    cleaner (``main.py clean``) writes the indexable copy.
        output_format: Output format passed to marker_single (default ``markdown``).

    Returns:
        List of absolute paths to the generated markdown files.
    """
    pdf_dir_value = pdf_dir if pdf_dir is not None else str(config.get("paths.raw_data", "data/0_raw"))
    output_dir_value = output_dir if output_dir is not None else os.path.join(str(config.get("paths.markdown_data", "data/1_markdown")), "_raw")
    os.makedirs(output_dir_value, exist_ok=True)

    pdf_files = sorted(glob.glob(os.path.join(pdf_dir_value, "**", "*.pdf"), recursive=True))
    if not pdf_files:
        logger.warning("No PDF files found in %s", pdf_dir_value)
        return []

    logger.info("Found %d PDF files to process in %s", len(pdf_files), pdf_dir_value)

    generated: List[str] = []

    for pdf_path in pdf_files:
        basename = os.path.basename(pdf_path)
        logger.info("Processing %s …", basename)

        command = [
            "marker_single",
            pdf_path,
            "--output_dir", output_dir_value,
            "--output_format", output_format,
            "--use_llm",
            "--disable_image_extraction",
        ]

        try:
            subprocess.run(command, check=True, capture_output=True, text=True)
            logger.info("Successfully processed %s", basename)

            # Remove any images generated by marker
            for ext in ("*.png", "*.jpg", "*.jpeg"):
                for img in glob.glob(os.path.join(output_dir_value, "**", ext), recursive=True):
                    os.remove(img)

            # Collect generated markdown files
            md_pattern = os.path.join(output_dir_value, "**", "*.md")
            for md_path in glob.glob(md_pattern, recursive=True):
                if md_path not in generated:
                    strip_images_in_file(md_path)
                    generated.append(md_path)

        except FileNotFoundError:
            logger.error(
                "marker_single not found. Install it with: pip install marker-pdf"
            )
            break
        except subprocess.CalledProcessError as exc:
            logger.error("Error processing %s: %s", basename, exc.stderr or exc)

    logger.info(
        "Parsing complete – %d PDFs processed, %d markdown files generated",
        len(pdf_files),
        len(generated),
    )
    return sorted(generated)
