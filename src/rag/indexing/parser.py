"""
PDF-to-Markdown parser using marker_single CLI tool.

Wraps the existing marker_single subprocess call with proper logging,
return values, and integration with the config system.
"""

import glob
import logging
import os
import subprocess
from typing import List, Optional

from src.utils.config_loader import config

logger = logging.getLogger(__name__)


def parse_pdfs(
    pdf_dir: Optional[str] = None,
    output_dir: Optional[str] = None,
    output_format: str = "markdown",
) -> List[str]:
    """
    Parse all PDF files in *pdf_dir* and convert them to markdown via ``marker_single``.

    Args:
        pdf_dir: Directory containing the source PDFs.
                 Falls back to ``config.paths.raw_data``.
        output_dir: Where to write the generated ``.md`` files.
                    Falls back to ``config.paths.markdown_data``.
        output_format: Output format passed to marker_single (default ``markdown``).

    Returns:
        List of absolute paths to the generated markdown files.
    """
    pdf_dir = pdf_dir or config.get("paths.raw_data", "data/0_raw")
    output_dir = output_dir or config.get("paths.markdown_data", "data/1_markdown")
    os.makedirs(output_dir, exist_ok=True)

    pdf_files = sorted(glob.glob(os.path.join(pdf_dir, "**", "*.pdf"), recursive=True))
    if not pdf_files:
        logger.warning("No PDF files found in %s", pdf_dir)
        return []

    logger.info("Found %d PDF files to process in %s", len(pdf_files), pdf_dir)

    generated: List[str] = []

    for pdf_path in pdf_files:
        basename = os.path.basename(pdf_path)
        logger.info("Processing %s …", basename)

        command = [
            "marker_single",
            pdf_path,
            "--output_dir", output_dir,
            "--output_format", output_format,
            "--use_llm",
        ]

        try:
            subprocess.run(command, check=True, capture_output=True, text=True)
            logger.info("Successfully processed %s", basename)

            # Remove any images generated by marker
            for ext in ("*.png", "*.jpg", "*.jpeg"):
                for img in glob.glob(os.path.join(output_dir, "**", ext), recursive=True):
                    os.remove(img)

            # Collect generated markdown files
            md_pattern = os.path.join(output_dir, "**", "*.md")
            for md_path in glob.glob(md_pattern, recursive=True):
                if md_path not in generated:
                    generated.append(md_path)

        except FileNotFoundError:
            logger.error(
                "marker_single not found. Install it with: pip install marker-pdf"
            )
            break
        except subprocess.CalledProcessError as exc:
            logger.error("Error processing %s: %s", basename, exc.stderr or exc)

    logger.info(
        "Parsing complete – %d PDFs processed, %d markdown files generated",
        len(pdf_files),
        len(generated),
    )
    return sorted(generated)
