"""Thesis tables from the headline test results (code 0293a0b), written to data/eval/extras/headline-analysis.md.

1. RQ5: every closed-book, strong and assistant rung against `current`, paired per question.
2. Results card: `current` by question type, and on the unanswerable questions.
3. Cost (RQ4): per answer, the pipeline's own LLM spend, tokens, calls and latency; judging apart.

Query analysis and expansion are cached per process (query_analyzer.py), so in one `eval` call only
the first rung that needs them logs their calls. Those costs are imputed per question from the rung
that logged them (dense_only), for every rung whose config uses the stage.
Usage: python scripts/eval_extras/headline_analysis.py
"""
import glob, json, statistics, sys
sys.path.insert(0, ".")
from src.rag.evaluation.models import VariantResult
from src.rag.evaluation.stats import bootstrap_ci, paired_diff, per_question

OUT = "data/eval/extras/headline-analysis.md"
LADDER = ["naive", "multiquery", "routed", "dense_only", "hybrid", "contextual", "current", "reranked"]
RQ5 = ["no_retrieval", "no_retrieval_strong", "current_strong", "assistant_gpt", "assistant_gemini",
       "assistant_claude", "deep_research_claude"]
GEN = ["correctness_recall", "correctness", "answer_relevance", "abstention", "false_refusal"]
CARD = ["recall", "ndcg", "aspect_recall", "faithfulness", "correctness", "correctness_recall",
        "correctness_grounded", "answer_relevance", "false_refusal"]

latest = {}
for f in sorted(glob.glob("data/eval/results/*-2026102*.json")):
    d = json.load(open(f))
    if d.get("split") == "test" and d.get("code_version") == "0293a0b":
        latest[d["variant"]] = VariantResult.model_validate(d)
gold = {q["id"]: q for q in json.load(open("data/eval/questions/golden.json"))["questions"] if q["split"] == "test"}


def cell(values):
    if not values:
        return ""
    ci = bootstrap_ci(values)
    m = statistics.fmean(values)
    return f"{m:.3f}" + (f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else "")


def delta(base, other, metric):
    d = paired_diff(per_question(base, metric), per_question(other, metric))
    if d is None or d[1] is None:
        return ""
    mean, (lo, hi), n = d
    s = f"{mean:+.3f} [{lo:+.2f}, {hi:+.2f}]"
    return f"**{s}**" if lo > 0 or hi < 0 else s


lines = ["# Headline analysis (test split, code `0293a0b`)", "",
         "Generated by `scripts/eval_extras/headline_analysis.py` from the committed results. "
         "Means with 95% bootstrap intervals over questions; deltas are paired per question "
         "(variant − `current`), **bold** when the interval excludes 0.", ""]

# 1. RQ5
cur = latest["current"]
lines += ["## 1. Retrieval versus scale (RQ5): every rung against `current`", "",
          "| variant | n | " + " | ".join(GEN) + " |", "| --- | --- |" + " --- |" * len(GEN),
          "| current | " + str(len(cur.per_question)) + " | "
          + " | ".join(cell(list(per_question(cur, m).values())) for m in GEN) + " |"]
for v in RQ5:
    r = latest[v]
    lines.append(f"| {v} | {len(r.per_question)} | " + " | ".join(cell(list(per_question(r, m).values())) for m in GEN) + " |")
lines += ["", "Paired difference against `current`:", "",
          "| variant | " + " | ".join(GEN) + " |", "| --- |" + " --- |" * len(GEN)]
for v in RQ5:
    lines.append(f"| {v} | " + " | ".join(delta(cur, latest[v], m) for m in GEN) + " |")
lines += ["", "`abstention` is scored on the 4 unanswerable questions only, `false_refusal` on the 32 "
          "answerable ones; faithfulness and retrieval metrics do not apply to closed-book rungs.", ""]

# 2. Results card
groups = {}
for qid, q in gold.items():
    groups.setdefault(q["query_type"] if q["answerable"] else "unanswerable", set()).add(qid)
order = ["single_party", "comparison", "topic_exploration", "general", "unanswerable"]
lines += ["## 2. Results card: `current` by question type", "",
          "| group | n | " + " | ".join(CARD + ["abstention"]) + " |", "| --- | --- |" + " --- |" * (len(CARD) + 1)]
for g in ["all answerable"] + order:
    ids = set(gold) - groups["unanswerable"] if g == "all answerable" else groups[g]
    row = [cell([r.metrics[m] for r in cur.per_question if r.question_id in ids and m in r.metrics])
           for m in CARD + ["abstention"]]
    lines.append(f"| {g} | {len(ids)} | " + " | ".join(row) + " |")
lines += ["", "Single-party unanswerable questions (3) and one topic question are in `unanswerable`; "
          "with n = 4 to 13 per group the intervals are wide.", ""]

# 3. Cost
def stage_costs(run_name, step):
    """Per question: (cost, tokens in, tokens out) of one logged stage."""
    return {r.question_id: tuple(sum(c[k] for c in r.llm_calls if c["step"] == step)
                                 for k in ("cost", "prompt_tokens", "completion_tokens"))
            for r in latest[run_name].per_question}


imputed = {"use_query_analysis": stage_costs("dense_only", "query analysis"),
           "use_multi_query": stage_costs("dense_only", "query expansion")}
logged = {"use_query_analysis": "query analysis", "use_multi_query": "query expansion"}
lines += ["## 3. Cost per answer (RQ4)", "",
          "| variant | pipeline $/answer | judge $/answer | tokens in | tokens out | LLM calls | latency mean (s) | latency median (s) | answers truncated |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
for v in LADDER + ["hybrid_only", "reranked_only"] + RQ5:
    r = latest[v]
    n = len(r.per_question)
    pipe = judge = tin = tout = calls = 0.0
    for q in r.per_question:
        own = [c for c in q.llm_calls if not c["step"].startswith("judge")]
        pipe += sum(c["cost"] for c in own)
        judge += sum(c["cost"] for c in q.llm_calls if c["step"].startswith("judge"))
        tin += sum(c["prompt_tokens"] for c in own)
        tout += sum(c["completion_tokens"] for c in own)
        calls += len(own)
        for flag, step in logged.items():  # stage cached by an earlier rung of the same process
            if r.config.get(flag) and r.config.get("use_retrieval", True) and not any(c["step"] == step for c in own):
                c_, i_, o_ = imputed[flag].get(q.question_id, (0.0, 0, 0))
                pipe, tin, tout, calls = pipe + c_, tin + i_, tout + o_, calls + 1
    lat = [q.latency_s for q in r.per_question if q.latency_s is not None]
    trunc = sum(any("[truncated]" in c["step"] for c in q.llm_calls) for q in r.per_question)
    note = " (notional, Claude plan)" if v == "deep_research_claude" else ""
    lines.append(f"| {v} | {pipe / n:.4f}{note} | {judge / n:.4f} | {tin / n:,.0f} | {tout / n:,.0f} | "
                 f"{calls / n:.1f} | {statistics.fmean(lat):.1f} | {statistics.median(lat):.1f} | {trunc} |")
lines += ["", "Pipeline cost is what answering costs (analysis, expansion, generation); judging is evaluation "
          "overhead. Cached stages add their imputed cost, tokens and one call. Latency excludes judging "
          "but includes provider retries (most of Gemini's mean). `answers truncated` counts answers "
          "that hit the 3,000-token cap (`llm.openrouter.max_tokens`). Assistant cost includes the "
          "provider's web-search fee; deep research is Claude Code's notional `total_cost_usd`.", ""]

open(OUT, "w").write("\n".join(lines))
print(OUT)
