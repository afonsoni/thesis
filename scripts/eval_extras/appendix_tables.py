import re

def md_table(path, start_marker):
    lines = open(path, encoding="utf-8").read().split("\n")
    i = next(k for k, l in enumerate(lines) if l.startswith(start_marker))
    i = next(k for k in range(i, len(lines)) if lines[k].startswith("| variant"))
    head = [c.strip() for c in lines[i].strip("|").split("|")]
    rows = {}
    for l in lines[i + 2:]:
        if not l.startswith("|"): break
        cells = [c.strip() for c in l.strip("|").split("|")]
        rows[cells[0]] = dict(zip(head, cells))
    return rows

