def tt(v): return "\\texttt{" + v.replace("_", "\\_") + "}"
def cell(s):
    m = re.match(r"^([+-]?[0-9.]+)\s*\[([^\]]+)\]$", s or "")
    if m: return f"{m.group(1)} {{\\scriptsize[{m.group(2)}]}}"
    return s.replace("$", "\\$") if s else "--"

def table(short, caption, label, cols, heads, variants, src, note=""):
    spec = "|l|" + "r|" * len(cols)
    out = ["\\begin{table}[H]", "    \\centering", "    \\footnotesize", "    \\begin{adjustbox}{max width=\\textwidth}",
           f"    \\begin{{tabular}}{{{spec}}}", "        \\hline",
           "        \\textbf{Variant} & " + " & ".join(f"\\textbf{{{h}}}" for h in heads) + " \\\\", "        \\hline"]
    for v in variants:
        if v in src:
            out.append("        " + tt(v) + " & " + " & ".join(cell(src[v].get(c, "")) for c in cols) + " \\\\")
    out += ["        \\hline", "    \\end{tabular}", "    \\end{adjustbox}",
            f"    \\caption[{short}]{{{caption}}}", f"    \\label{{{label}}}", "\\end{table}", ""]
    return "\n".join(out)

