#!/usr/bin/env python3
"""Regenerate dissertation/WRITING-TODO.md from the \\TODO markers in the LaTeX source.

The LaTeX files are the single source of truth: a writing task exists exactly as
long as its \\TODO{...} does. Write the section, delete the marker, rerun this,
and the item disappears from the list.

    python3 scripts/writing_todo.py            # rewrite WRITING-TODO.md
    python3 scripts/writing_todo.py --print    # print to stdout, write nothing
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DISSERTATION = ROOT / "dissertation"
OUTPUT = DISSERTATION / "WRITING-TODO.md"

# Order matters: it is the order a reader meets the chapters.
SEARCH_ORDER = [
    "chapters/Introduction.tex",
    "chapters/StateOfTheArt.tex",
    "chapters/ProblemAndChallenges.tex",
    "chapters/Proposition.tex",
    "chapters/Results.tex",
    "chapters/ConclusionsAndFutureWork.tex",
    "preamble/Abstract.tex",
    "appendices/DetailsOfResults.tex",
    "appendices/Tooling.tex",
]


def find_todos(text: str) -> list[tuple[int, str]]:
    """Return (line number, content) for each \\TODO{...}, brace-matched."""
    todos = []
    for match in re.finditer(r"\\TODO\{", text):
        start = match.end()
        depth = 1
        index = start
        while index < len(text) and depth:
            char = text[index]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
            index += 1
        body = text[start : index - 1]
        line_number = text.count("\n", 0, match.start()) + 1
        todos.append((line_number, tidy(body)))
    return todos


def tidy(body: str) -> str:
    """Flatten LaTeX markup into something readable in a markdown list."""
    body = re.sub(r"\s+", " ", body).strip()
    body = body.replace("---", "—").replace("~", " ")
    body = re.sub(r"\\ref\{([^}]*)\}", r"`\1`", body)
    body = re.sub(r"\\(?:textbf|texttt|emph)\{([^}]*)\}", r"**\1**", body)
    body = re.sub(r"\$?\\rightarrow\$?", "→", body)
    body = re.sub(r"\\times", "×", body)
    body = body.replace("\\%", "%").replace("\\&", "&").replace("\\_", "_")
    body = body.replace("\\", "").replace("$", "")
    return re.sub(r"\s+", " ", body).strip()


def main() -> int:
    files = [p for p in SEARCH_ORDER if (DISSERTATION / p).exists()]
    # Catch any file not in SEARCH_ORDER so nothing is silently missed.
    known = set(files)
    for path in sorted(DISSERTATION.rglob("*.tex")):
        rel = path.relative_to(DISSERTATION).as_posix()
        if rel not in known and "\\TODO{" in path.read_text(encoding="utf-8"):
            files.append(rel)

    sections, total = [], 0
    for rel in files:
        todos = find_todos((DISSERTATION / rel).read_text(encoding="utf-8"))
        if not todos:
            continue
        total += len(todos)
        lines = [f"## {rel} ({len(todos)})", ""]
        lines += [f"- **L{line}** — {body}" for line, body in todos]
        sections.append("\n".join(lines))

    body = "\n\n".join(sections) if sections else "Nothing left. Every marker is gone."
    document = (
        "# Writing TODO\n\n"
        "_Generated by `scripts/writing_todo.py` — do not edit by hand._\n"
        "_The LaTeX sources are the source of truth: delete a `\\TODO{...}` "
        "once that passage is written, then rerun the script._\n\n"
        f"**{total} open** across {len(sections)} files. "
        "Standing decisions that are not passages to write live in "
        "`dissertation/DECISIONS.md`.\n\n"
        f"{body}\n"
    )

    if "--print" in sys.argv:
        print(document)
    else:
        OUTPUT.write_text(document, encoding="utf-8")
        print(f"[todo] wrote {OUTPUT.relative_to(ROOT)} — {total} open items")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
